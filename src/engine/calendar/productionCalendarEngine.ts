export function getSeasonMilestoneSummary(
  currentTime: TimeState,
  events: SeasonTimelineEvent[] = FULL_SEASON_ROADMAP
): SeasonMilestoneSummary {
  const currentTotalDay = currentTime.day;
  const currentWeek = currentTime.week;
  const totalDays = 84;
  const daysRemaining = Math.max(0, totalDays - currentTotalDay);

  const upcoming = events.filter((ev) => ev.day >= currentTotalDay);
  const completed = events.filter((ev) => ev.day < currentTotalDay);

  const nextEvictionEvent = upcoming.find((ev) => ev.category === 'eviction');
  const nextChallengeEvent = upcoming.find((ev) => ev.category === 'challenge');
  const nextPlotTwistEvent = upcoming.find((ev) => ev.category === 'plot_twist');

  return {
    totalWeeks: 12,
    totalDays,
    currentDay: currentTotalDay,
    currentWeek,
    daysRemaining,
    nextEvictionEvent,
    nextChallengeEvent,
    nextPlotTwistEvent,
    completedEventsCount: completed.length,
    upcomingEventsCount: upcoming.length,
  };
}

export function calculateEventProductionCost(
  event: SeasonTimelineEvent,
  strategy: ProductionStrategyOption
): number {
  return event.baseCost + strategy.cost;
}

export function calculateEventExpectedIbope(
  event: SeasonTimelineEvent,
  baseIbope: number,
  strategy: ProductionStrategyOption
): number {
  return Number((baseIbope + event.expectedIbope.baseBoost + strategy.ibopeBonus).toFixed(1));
}
